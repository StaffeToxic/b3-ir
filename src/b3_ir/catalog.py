"""Bundled asset catalog built from B3 COTAHIST (research D-R4-2).

Answers two questions offline (Constitution IV): the asset class of a ticker, and
which ticker a brokerage note means by a trading name such as "BBSEGURIDADE ON NM".
The data file is regenerated by scripts/atualizar_ativos.py.
"""

from __future__ import annotations

import csv
import re
from collections import defaultdict
from dataclasses import dataclass
from functools import cache
from importlib.resources import files

from b3_ir.domain.models import AssetClass

# Event marks B3 appends to the specification ("ON EJ NM": ex-interest, "ED":
# ex-dividend, "ATZ": updated...) and the market-segment noise notes may carry.
_MARKS = re.compile(r"^(E[A-Z]{1,2}|ATZ|CI|#\S*)$")


def normalize_name(text: str) -> str:
    """Canonical key for a trading name + specification, used on both sides."""
    tokens = text.upper().replace(".", "").split()
    return " ".join(token for token in tokens if not _MARKS.match(token))


@dataclass(frozen=True)
class Catalog:
    asset_classes: dict[str, AssetClass]
    names: dict[str, frozenset[str]]

    def ticker_for_name(self, name: str) -> str | None:
        """The single ticker for a note's trading name, or None if unknown or ambiguous."""
        tickers = self.names.get(normalize_name(name), frozenset())
        return next(iter(tickers)) if len(tickers) == 1 else None


@cache
def load_catalog() -> Catalog:
    text = files("b3_ir.data").joinpath("ativos.csv").read_text(encoding="utf-8")
    classes: dict[str, AssetClass] = {}
    names: dict[str, set[str]] = defaultdict(set)
    for row in csv.DictReader(text.splitlines(), delimiter=";"):
        ticker = row["ticker"]
        classes[ticker] = AssetClass(row["classe"])
        if row["nome_pregao"]:
            names[normalize_name(f"{row['nome_pregao']} {row['especificacao']}")].add(ticker)
    return Catalog(classes, {key: frozenset(value) for key, value in names.items()})
